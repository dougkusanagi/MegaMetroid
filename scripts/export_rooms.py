"""Generate the room sources from the Tiled maps in rooms/ (etapa 6.2).

Each rooms/<id>.tmj is a Tiled JSON map (8x8 tiles). It holds everything that used
to be edited by hand in src/map_<id>.c:

  tile layer   "collision"  gid = collision value + 1 (rooms/collision.tsj: 0 solid,
                            1 open, 2 slope rising right, 3 slope rising left)
  object layer "spawn"      one point, in pixels (Samus' upper-left start position)
  object layer "camera"     rectangles = trigger; properties bounds_left/top/right/bottom
  object layer "doors"      rectangles (upper-left = position); properties color,
                            facing and link (optional): index of the door in the room's
                            node of rooms/world.json. The route and the arrival point
                            come from that graph (a door whose far room is not built yet
                            has no destination)
  object layer "enemies"    points; property kind (u16)
  map properties            fg_image, bg_image (relative to res/images),
                            background_scroll_height (0: background fixed),
                            world_node (optional): the Super Metroid room of rooms/world.json
                            this map is (or stands in for)

Outputs (all committed, each with a "generated" banner): src/map_<id>.c,
inc/map_<id>.h, res/<id>.res and, for the whole set, inc/map.h and src/map.c.
Room order (and so the ROOM_* numbers) comes from rooms/index.json.

  python scripts/export_rooms.py             write the files
  python scripts/export_rooms.py --check     fail if a committed file is out of date
  python scripts/export_rooms.py tileset     (re)write rooms/collision.{png,tsj}

Workflow: edit the .tmj in Tiled (tile layer format CSV), run this script, rebuild.
"""
from pathlib import Path
import argparse
import json
import re
import struct
import sys

import world_graph

ROOT = Path(__file__).resolve().parents[1]
TILE = 8
COLLISION_NAMES = ['solid', 'open', 'slope_rise_right', 'slope_rise_left']
DOOR_COLORS = ['blue', 'red', 'green']
DOOR_FACINGS = ['left', 'right', 'up', 'down']
# The side of a room a door sits on, by the way its shell faces (the node doors name the wall).
FACING_WALL = {'right': 'left', 'left': 'right', 'down': 'top', 'up': 'bottom'}
# Samus' upper-left corner on arrival, from the door's upper-left, by the wall the door is on.
ARRIVAL_OFFSET = {'left': (24, 16), 'right': (-32, 16)}
BLOCK = 16
# Footprint of a door (mm_door_rect in src/core/door.c): depth across the opening, length along the wall.
DOOR_DEPTH, DOOR_LENGTH = 32, 64
BANNER = 'Generated by scripts/export_rooms.py from rooms/{src}. Do not edit; change the map and regenerate.'


class RoomError(Exception):
    pass


def props(obj):
    """Tiled custom properties as a dict."""
    return {p['name']: p['value'] for p in obj.get('properties', [])}


def need(cond, room, message):
    if not cond:
        raise RoomError(f'{room}: {message}')


def image_size(path):
    data = path.read_bytes()
    if data[:8] == b'\x89PNG\r\n\x1a\n':
        return struct.unpack('>II', data[16:24])
    if data[:2] == b'BM':
        w, h = struct.unpack('<ii', data[18:26])
        return w, abs(h)
    return None


def int_prop(p, name, room, lo=None, hi=None, default=None):
    value = p.get(name, default)
    need(isinstance(value, int) and not isinstance(value, bool), room, f'property {name} must be an integer')
    need(lo is None or value >= lo, room, f'property {name} below {lo}')
    need(hi is None or value <= hi, room, f'property {name} above {hi}')
    return value


def load_room(path, root=ROOT, world=None):
    """Parse and validate one .tmj; returns the data the templates need."""
    rid = path.stem
    need(re.fullmatch(r'[a-z][a-z0-9_]*', rid), rid, 'file name must be a lowercase C identifier')
    doc = json.loads(path.read_text(encoding='utf-8'))
    need(doc.get('orientation') == 'orthogonal' and not doc.get('infinite'), rid, 'map must be orthogonal and finite')
    need(doc.get('tilewidth') == TILE and doc.get('tileheight') == TILE, rid, f'tiles must be {TILE}x{TILE}')
    cols, rows = doc['width'], doc['height']
    need(cols > 0 and rows > 0, rid, 'empty map')
    tilesets = doc.get('tilesets', [])
    need(len(tilesets) == 1 and tilesets[0].get('firstgid') == 1 and tilesets[0].get('source') == 'collision.tsj',
         rid, 'tilesets must be exactly collision.tsj with firstgid 1')
    layers = {layer['name']: layer for layer in doc['layers']}
    for name, kind in [('collision', 'tilelayer'), ('spawn', 'objectgroup'), ('camera', 'objectgroup'),
                       ('doors', 'objectgroup'), ('enemies', 'objectgroup')]:
        need(name in layers and layers[name]['type'] == kind, rid, f'missing {kind} "{name}"')

    layer = layers['collision']
    need(layer.get('encoding', 'csv') == 'csv' and not layer.get('compression') and isinstance(layer.get('data'), list),
         rid, 'collision data must be CSV (Tiled: Map Properties > Tile Layer Format = CSV)')
    need(layer['width'] == cols and layer['height'] == rows and len(layer['data']) == cols * rows,
         rid, 'collision layer does not cover the whole map')
    values = []
    for index, gid in enumerate(layer['data']):
        need(isinstance(gid, int) and 1 <= gid <= len(COLLISION_NAMES), rid,
             f'collision cell ({index % cols},{index // cols}) is empty or not a collision tile (gid {gid})')
        values.append(gid - 1)

    width_px, height_px = cols * TILE, rows * TILE
    p = props(doc)
    images = {}
    for key in ('fg_image', 'bg_image'):
        need(isinstance(p.get(key), str) and p[key], rid, f'map property {key} missing')
        need((root / 'res/images' / p[key]).is_file(), rid, f'{key} not found: res/images/{p[key]}')
        images[key] = p[key]
    size = image_size(root / 'res/images' / images['fg_image'])
    need(size == (width_px, height_px), rid, f'fg_image is {size}, map is {(width_px, height_px)} pixels')
    scroll = int_prop(p, 'background_scroll_height', rid, lo=0, default=0)

    spawns = layers['spawn']['objects']
    need(len(spawns) == 1 and spawns[0].get('point'), rid, 'spawn layer needs exactly one point')
    spawn = (round(spawns[0]['x']), round(spawns[0]['y']))
    need(0 <= spawn[0] < width_px and 0 <= spawn[1] < height_px, rid, 'spawn outside the map')

    zones = []
    for obj in layers['camera']['objects']:
        q = props(obj)
        trigger = [round(obj['x']), round(obj['y']), round(obj['x'] + obj['width']), round(obj['y'] + obj['height'])]
        bounds = [int_prop(q, f'bounds_{side}', rid) for side in ('left', 'top', 'right', 'bottom')]
        for rect, what in ((trigger, 'trigger'), (bounds, 'bounds')):
            need(rect[0] < rect[2] and rect[1] < rect[3], rid, f'camera zone {what} is empty')
            need(rect[0] >= 0 and rect[1] >= 0 and rect[2] <= width_px and rect[3] <= height_px, rid,
                 f'camera zone {what} outside the map')
        zones.append((trigger, bounds))

    node = None
    if 'world_node' in p:
        nodes = world_graph.nodes_by_id(world)
        need(p['world_node'] in nodes, rid, f'world_node "{p["world_node"]}" is not a room in rooms/world.json')
        node = nodes[p['world_node']]
    doors = []
    for obj in layers['doors']['objects']:
        q = props(obj)
        need(q.get('color') in DOOR_COLORS, rid, f'door color must be one of {DOOR_COLORS}')
        need(q.get('facing') in DOOR_FACINGS, rid, f'door facing must be one of {DOOR_FACINGS}')
        x, y = round(obj['x']), round(obj['y'])
        w, h = (DOOR_LENGTH, DOOR_DEPTH) if q['facing'] in ('up', 'down') else (DOOR_DEPTH, DOOR_LENGTH)
        need(x >= 0 and y >= 0 and x + w <= width_px and y + h <= height_px, rid,
             f'door at ({x},{y}) outside the map')
        link = None
        if 'link' in q:
            need(node is not None, rid, 'door link needs the map property world_node')
            link = int_prop(q, 'link', rid, lo=0, hi=len(node['doors']) - 1)
            door = node['doors'][link]
            need(door['wall'] == FACING_WALL[q['facing']], rid,
                 f'door {link} of {node["id"]} is on the {door["wall"]} wall; a {q["facing"]}-facing door is not')
            if door['wall'] in ARRIVAL_OFFSET:
                shell = door['at'][0] - (1 if door['wall'] == 'left' else 0), door['at'][1]
                need((x // BLOCK, y // BLOCK) == shell, rid,
                     f'door {link} of {node["id"]} belongs at block {shell}, the map has it at ({x // BLOCK},{y // BLOCK})')
        doors.append(dict(x=x, y=y, link=link, color=q['color'], facing=q['facing']))
    if node:
        linked = sorted(d['link'] for d in doors if d['link'] is not None)
        need(len(set(linked)) == len(linked), rid, 'two doors share one link')
        missing = [i for i in range(len(node['doors'])) if i not in linked]
        need(not missing, rid, f'doors {missing} of {node["id"]} have no door in the map')

    enemies = []
    for obj in layers['enemies']['objects']:
        q = props(obj)
        x, y = round(obj['x']), round(obj['y'])
        need(0 <= x < width_px and 0 <= y < height_px, rid, f'enemy at ({x},{y}) outside the map')
        enemies.append((int_prop(q, 'kind', rid, lo=0, hi=0xFFFF), x, y))

    return dict(id=rid, node=p.get('world_node'), cols=cols, rows=rows, width=width_px, height=height_px, values=values, images=images,
                scroll=scroll, spawn=spawn, zones=zones, doors=doors, enemies=enemies)


def resolve_routes(rooms, world):
    """Give every linked door its destination room and arrival point, from the world graph."""
    nodes = world_graph.nodes_by_id(world)
    by_node = {}
    for r in rooms:
        if r['node']:
            need(r['node'] not in by_node, r['id'], f'world_node {r["node"]} is also used by {by_node.get(r["node"], {}).get("id")}')
            by_node[r['node']] = r
    for r in rooms:
        for d in r['doors']:
            d['target'], d['tx'], d['ty'] = '', 0, 0
            if d['link'] is None:
                continue
            far = nodes[r['node']]['doors'][d['link']]
            built = by_node.get(far['to'])
            if built is None:
                continue
            arrival = next((e for e in built['doors'] if e['link'] == far['peer']), None)
            wall = nodes[built['node']]['doors'][far['peer']]['wall']
            need(wall in ARRIVAL_OFFSET, r['id'], f'arrival at a {wall} wall door is not defined yet')
            dx, dy = ARRIVAL_OFFSET[wall]
            d['target'], d['tx'], d['ty'] = built['id'], arrival['x'] + dx, arrival['y'] + dy


def load_all(root=ROOT):
    order = json.loads((root / 'rooms/index.json').read_text(encoding='utf-8'))
    need(isinstance(order, list) and order and len(set(order)) == len(order), 'index.json',
         'must list unique room ids')
    try:
        world = world_graph.load(root)
        world_graph.validate(world)
    except world_graph.WorldError as error:
        raise RoomError(f'world.json: {error}')
    rooms = [load_room(root / 'rooms' / f'{rid}.tmj', root, world) for rid in order]
    extra = {p.stem for p in (root / 'rooms').glob('*.tmj')} - set(order)
    need(not extra, 'index.json', f'rooms not listed: {sorted(extra)}')
    resolve_routes(rooms, world)
    return rooms


# ---------------------------------------------------------------- templates

def render_c(r):
    rid, cols, rows = r['id'], r['cols'], r['rows']
    out = [f'/* {BANNER.format(src=rid + ".tmj")} */',
           '#include <genesis.h>', '',
           '#include "../inc/types.h"',
           f'#include "../res/{rid}.h"',
           '#include "../inc/map.h"',
           '#include "../res/resources.h"', '',
           f'const u8 map_collision_{rid}[{rows}][{cols}] = {{']
    for y in range(rows):
        out.append('  {' + ', '.join(str(v) for v in r['values'][y * cols:(y + 1) * cols]) + '},')
    out += ['};', '']
    if r['zones']:
        out.append(f'static const MmCameraZone {rid}_camera_zones[] = {{')
        out.append(',\n'.join('    {{%d, %d, %d, %d}, {%d, %d, %d, %d}}' % tuple(t + b) for t, b in r['zones']))
        out += ['};', '']
    if r['doors']:
        out.append(f'static const RoomDoorDef {rid}_doors[] = {{')
        entries = []
        for d in r['doors']:
            target = f'ROOM_{d["target"].upper()}' if d['target'] else 'ROOM_NO_CONNECTION'
            entries.append('    {{%d, %d}, %s, {%d, %d}, ROOM_DOOR_%s, ROOM_DOOR_FACING_%s}' %
                           (d['x'], d['y'], target, d['tx'], d['ty'], d['color'].upper(), d['facing'].upper()))
        out += [',\n'.join(entries), '};', '']
    if r['enemies']:
        out.append(f'static const RoomEnemySpawn {rid}_enemies[] = {{')
        out += [',\n'.join('    {%d, {%d, %d}}' % e for e in r['enemies']), '};', '']

    def ref(items, name, count_name, table):
        if items:
            return [f'    .{name} = {table},', f'    .{count_name} = sizeof({table}) / sizeof({table}[0]),']
        return [f'    .{name} = NULL,', f'    .{count_name} = 0,']

    out += [f'const room_def room_{rid} = {{',
            f'    .tileset_fg = &{rid}_fg_tileset,', f'    .tileset_bg = &{rid}_bg_tileset,',
            f'    .image_fg = &{rid}_fg_image,', f'    .image_bg = &{rid}_bg_image,',
            f'    .map_fg = &{rid}_fg_map,', f'    .map_bg = &{rid}_bg_map,',
            f'    .palette_fg = &{rid}_fg_palette,', f'    .palette_bg = &{rid}_bg_palette,',
            f'    .map_width = {r["width"]},', f'    .map_height = {r["height"]},',
            f'    .background_scroll_height = {r["scroll"]},',
            f'    .map_collision = &map_collision_{rid}[0][0],',
            '    .player_initial_pos = {%d, %d},' % r['spawn']]
    out += ref(r['zones'], 'camera_zones', 'camera_zone_count', f'{rid}_camera_zones')
    out += ref(r['enemies'], 'enemy_spawns', 'enemy_spawn_count', f'{rid}_enemies')
    out += ref(r['doors'], 'doors', 'door_count', f'{rid}_doors')
    out += ['};', '']
    return '\n'.join(out)


def render_header(r):
    rid = r['id']
    return '\n'.join([f'/* {BANNER.format(src=rid + ".tmj")} */', '#pragma once', '#include <genesis.h>', '',
                      '#include "./types.h"', '',
                      f'extern const u8 map_collision_{rid}[{r["rows"]}][{r["cols"]}];', '',
                      f'extern const room_def room_{rid};', ''])


def render_res(r):
    rid = r['id']
    fg, bg = r['images']['fg_image'], r['images']['bg_image']
    lines = [f'# {BANNER.format(src=rid + ".tmj")}']
    for kind in ('IMAGE', 'PALETTE', 'TILESET'):
        for layer, path in (('fg', fg), ('bg', bg)):
            tail = '' if kind == 'PALETTE' else '\tBEST'
            lines.append(f'{kind}\t{rid}_{layer}_{kind.lower()}\t"images/{path}"{tail}')
        lines.append('')
    for layer, path in (('fg', fg), ('bg', bg)):
        lines.append(f'MAP\t{rid}_{layer}_map\t"images/{path}"\t{rid}_{layer}_tileset\tBEST')
    return '\n'.join(lines) + '\n'


def render_catalog_header(rooms):
    lines = [f'/* {BANNER.format(src="index.json")} */', '#pragma once', '#include "types.h"']
    lines += [f'#include "map_{r["id"]}.h"' for r in rooms]
    lines.append('')
    lines += [f'#define ROOM_{r["id"].upper()} {i}' for i, r in enumerate(rooms)]
    lines += [f'#define ROOM_COUNT {len(rooms)}', '', 'const room_def *room_get(u16 index);', '']
    return '\n'.join(lines)


def render_catalog_source(rooms):
    table = ', '.join(f'&room_{r["id"]}' for r in rooms)
    return '\n'.join([f'/* {BANNER.format(src="index.json")} */', '#include "map.h"', '',
                      'const room_def *room_get(u16 index)', '{',
                      f'    static const room_def * const rooms[ROOM_COUNT] = {{{table}}};',
                      '    return index < ROOM_COUNT ? rooms[index] : NULL;', '}', ''])


def generate(root=ROOT):
    """Relative path -> text of every generated file."""
    rooms = load_all(root)
    files = {'inc/map.h': render_catalog_header(rooms), 'src/map.c': render_catalog_source(rooms)}
    for r in rooms:
        files[f'src/map_{r["id"]}.c'] = render_c(r)
        files[f'inc/map_{r["id"]}.h'] = render_header(r)
        files[f'res/{r["id"]}.res'] = render_res(r)
    return files


# ------------------------------------------------------------ Tiled format

def dump_tmj(doc):
    """Tiled-style JSON, with tile data one map row per line so diffs show which cells changed."""
    grids = []

    def strip(node, key=None, parent=None):
        if key == 'data' and parent.get('type') == 'tilelayer':
            grids.append((parent['width'], node))
            return f'@@GRID{len(grids) - 1}@@'
        if isinstance(node, dict):
            return {k: strip(v, k, node) for k, v in node.items()}
        if isinstance(node, list):
            return [strip(v) for v in node]
        return node

    text = json.dumps(strip(doc), indent=1, ensure_ascii=False)
    for i, (width, data) in enumerate(grids):
        rows = [','.join(str(v) for v in data[o:o + width]) for o in range(0, len(data), width)]
        text = text.replace(f'"@@GRID{i}@@"', '[\n' + ',\n'.join(rows) + '\n]')
    return text + '\n'


def write_tileset(root=ROOT):
    from PIL import Image
    colors = [(120, 120, 120), (24, 24, 24), (200, 80, 60), (60, 120, 200)]
    image = Image.new('RGB', (TILE * len(colors), TILE))
    for i, color in enumerate(colors):
        for y in range(TILE):
            for x in range(TILE):
                if i == 2:
                    paint = y >= TILE - 1 - x
                elif i == 3:
                    paint = y >= x
                else:
                    paint = True
                image.putpixel((i * TILE + x, y), color if paint else (0, 0, 0))
    image.save(root / 'rooms/collision.png', optimize=True)
    tsj = {'type': 'tileset', 'version': '1.10', 'tiledversion': '1.10.2', 'name': 'collision', 'image': 'collision.png',
           'imagewidth': TILE * len(colors), 'imageheight': TILE, 'tilewidth': TILE, 'tileheight': TILE,
           'tilecount': len(colors), 'columns': len(colors), 'margin': 0, 'spacing': 0,
           'tiles': [{'id': i, 'type': name} for i, name in enumerate(COLLISION_NAMES)]}
    with open(root / 'rooms/collision.tsj', 'w', encoding='utf-8', newline='\n') as f:
        f.write(json.dumps(tsj, indent=1) + '\n')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('command', nargs='?', choices=['generate', 'tileset'], default='generate')
    ap.add_argument('--check', action='store_true', help='do not write; fail if files are out of date')
    ap.add_argument('--root', type=Path, default=ROOT)
    args = ap.parse_args(argv)
    if args.command == 'tileset':
        write_tileset(args.root)
        return 0
    try:
        files = generate(args.root)
    except RoomError as error:
        print(f'export_rooms: {error}', file=sys.stderr)
        return 1
    stale = []
    for rel, text in sorted(files.items()):
        path = args.root / rel
        # A checkout with core.autocrlf stores CRLF; the content is what matters.
        current = path.read_bytes().decode('utf-8').replace('\r\n', '\n') if path.exists() else None
        if current != text:
            stale.append(rel)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                with open(path, 'w', encoding='utf-8', newline='\n') as f:
                    f.write(text)
    if args.check:
        if stale:
            print('export_rooms: out of date (run python scripts/export_rooms.py): ' + ', '.join(stale), file=sys.stderr)
            return 1
        print(f'PASS {len(files)} generated room files match rooms/*.tmj')
    else:
        print(f'export_rooms: {len(stale)} of {len(files)} files written')
    return 0


if __name__ == '__main__':
    sys.exit(main())
